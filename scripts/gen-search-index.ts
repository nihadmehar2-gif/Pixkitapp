/**
 * Generates src/lib/tools/search-index.ts — a lightweight snapshot of the tool
 * registry used by CLIENT components (header search, dialog) so the full
 * registry (with SEO guides, FAQs, options) is never shipped to the browser.
 *
 * Re-run after adding/changing tools:  bun scripts/gen-search-index.ts
 */
import { TOOLS, CATEGORIES } from "../src/lib/tools";
import { writeFileSync } from "node:fs";

const items = TOOLS.map((t) => ({
  slug: t.slug,
  name: t.name,
  description: t.description,
  category: t.category,
  icon: t.icon,
  keywords: t.keywords,
  popular: t.popular || undefined,
}));

const counts: Record<string, number> = {};
for (const t of TOOLS) counts[t.category] = (counts[t.category] ?? 0) + 1;

const banner = `/**
 * AUTO-GENERATED by scripts/gen-search-index.ts — do not edit by hand.
 * Lightweight tool metadata for CLIENT bundles (header search, cmdk dialog).
 * The full registry (SEO guides, FAQs, options) stays server-side only.
 * Re-generate after tool changes: bun scripts/gen-search-index.ts
 */

import type { ToolCategory } from "./types";

export interface SearchItem {
  slug: string;
  name: string;
  description: string;
  category: ToolCategory["id"];
  icon: string;
  keywords: string[];
  popular?: boolean;
}

export const SEARCH_ITEMS: SearchItem[] = ${JSON.stringify(items, null, 2)};

export const CATEGORY_COUNTS: Record<string, number> = ${JSON.stringify(counts)};

export const TOOL_COUNT = ${TOOLS.length};
export const CATEGORY_COUNT = ${CATEGORIES.length};

/** Client-side search over the lightweight index (same scoring as server). */
export function searchIndexTools(query: string, limit = 30): SearchItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const terms = q.split(/\\s+/);
  const scored = SEARCH_ITEMS.map((tool) => {
    const haystack = \`\${tool.name} \${tool.slug} \${tool.description} \${tool.keywords.join(" ")}\`.toLowerCase();
    let score = 0;
    for (const term of terms) {
      if (tool.slug.includes(term)) score += 10;
      if (tool.name.toLowerCase().includes(term)) score += 8;
      if (tool.keywords.some((k) => k.toLowerCase().includes(term))) score += 5;
      if (haystack.includes(term)) score += 2;
    }
    return { tool, score };
  });
  return scored
    .filter((s) => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((s) => s.tool);
}
`;

writeFileSync(new URL("../src/lib/tools/search-index.ts", import.meta.url), banner);
console.log(`search-index.ts written: ${items.length} tools, ${CATEGORIES.length} categories`);
